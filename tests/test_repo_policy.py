"""Repository policy (AGENTS.md, Data policy) on every tracked file, and the CI pinning rules."""
import os
import re
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
BLOCKED = {
    "fonts": {".ttf", ".otf", ".ttc", ".woff", ".woff2"},
    "screenshots or crops": {".png", ".jpg", ".jpeg", ".webp", ".bmp", ".gif", ".tif", ".tiff"},
    "shards, datasets or archives": {".npz", ".npy", ".parquet", ".arrow", ".zip", ".tar", ".gz", ".xz", ".zst",
                                     ".7z"},
    "weights or checkpoints": {".pt", ".pth", ".ckpt", ".onnx", ".safetensors", ".tflite", ".bin", ".pdparams",
                               ".vocr", ".mnn"},
    "console binaries": {".vpk", ".self", ".velf", ".elf", ".suprx", ".skprx", ".prx", ".pbp", ".iso", ".cso"},
}
MAX_BYTES = 2 * 1024 * 1024
# Repo-relative paths that may break a rule above. Add one only with the reason in the PR body.
# The two vocab-expand curves are matplotlib plots of aggregate character counts (no screenshot or crop),
# generated by docs/vocab_expand_plots.py and committed small (< 50 KB each); see docs/vocab-expand.md.
# The README's VOCR-vs-OCRs chart (2x PNGs beside its SVGs, < 1 MB each) is a bar chart of committed scores,
# drawn by docs/charts/vocr_vs_lens.py; tests/test_vocr_vs_lens_chart.py checks its numbers.
ALLOWED = {"docs/benchmarks/vocab-coverage.png", "docs/benchmarks/vocab-cost.png",
           "docs/charts/vocr-vs-lens-light-2x.png", "docs/charts/vocr-vs-lens-dark-2x.png"}


def tracked():
    try:
        out = subprocess.run(["git", "ls-files", "-z", "-s"], cwd=ROOT, check=True, capture_output=True).stdout
    except (OSError, subprocess.CalledProcessError):
        pytest.skip("not a git checkout")
    entries = []
    for rec in out.decode().split("\0"):
        if rec:
            meta, path = rec.split("\t", 1)
            entries.append((meta.split()[0], path))       # (mode, path)
    return [(mode, path) for mode, path in entries if path not in ALLOWED]


def test_no_copyrighted_or_bulky_files_are_tracked():
    bad = []
    for _, path in tracked():
        kind = next((k for k, exts in BLOCKED.items() if Path(path).suffix.lower() in exts), None)
        if kind:
            bad.append(f"{path}: {kind} are never committed")
        elif (ROOT / path).is_file() and (ROOT / path).stat().st_size > MAX_BYTES:
            bad.append(f"{path}: {(ROOT / path).stat().st_size:,} bytes (limit {MAX_BYTES:,})")
    assert not bad, ("AGENTS.md: commit code, manifests (URLs + hashes), small tables and results; "
                     "weights go on releases.\n" + "\n".join(bad))


def test_no_tracked_symlinks_out_of_the_repo():
    """A committed symlink into $HERD/shared or a home directory works for nobody else."""
    bad = []
    for mode, path in tracked():
        if mode == "120000":
            target = os.readlink(ROOT / path)
            resolved = (ROOT / path).parent.joinpath(target).resolve()
            if os.path.isabs(target) or ROOT.resolve() not in resolved.parents:
                bad.append(f"{path} -> {target}")
    assert not bad, bad


# The repo is public: no tracked file may name an internal machine. Result files name the machine they ran on
# with train/hostinfo.py's generic label instead (docs/build-host.md). INTERNAL_HOST (the build machines'
# corporate cloud-desktop names, the corporate domain and EC2's internal DNS names) is written so that no tracked
# file, this one included, matches it; HOSTNAME_READ covers the usual ways code reads the machine's network name
# (Python, shell, make, C/C++). Both are guards against the usual forms, not proofs: a name built at run time
# (e.g. "HOST" "NAME") passes, and tests/test_hostinfo.py checks what the writers record.
INTERNAL_HOST = re.compile(rb"dev-ds[k]-|\.amazon\.com|\.(?:compute|ec2)\.internal\b|\bip-\d{1,3}(?:-\d{1,3}){3}\b",
                           re.IGNORECASE)
HOSTNAME_READ = re.compile(rb"platform\.(?:node|uname)\(|socket\.(?:gethostname|getfqdn)\(|os\.uname\(|\.nodename\b"
                           rb"|\bgethostname\(|\bgethostbyaddr\(|\bgetnameinfo\(|[\"'](?:HOSTNAME|hostname)[\"']"
                           rb"|/etc/hostname|\$\{?HOSTNAME\b|\$\(hostname\b|`hostname\b|\(shell +hostname\b"
                           rb"|\buname +(?:-[a-z]*[an]|--(?:all|nodename))|from +platform +import[^\n]*\bnode\b"
                           rb"|from +socket +import[^\n]*\b(?:gethostname|getfqdn)\b")
CODE_SUFFIXES = {".py", ".sh", ".c", ".h", ".cpp", ".hpp", ".cc", ".mk", ".cmake", ".yml", ".yaml"}
CODE_NAMES = {"Makefile", "CMakeLists.txt"}
# Code that may name those calls: this file (the patterns and their samples) and the test that checks that no
# writer records the name.
HOSTNAME_READ_ALLOWED = {"tests/test_repo_policy.py", "tests/test_hostinfo.py"}


def matches(pattern, paths):
    bad = []
    for path in paths:
        f = ROOT / path
        if f.is_file():
            data = f.read_bytes()
            for m in pattern.finditer(data):
                line = data.count(b"\n", 0, m.start()) + 1
                bad.append(f"{path}:{line}: {m.group().decode(errors='replace')}")
    return bad


def test_internal_host_patterns():
    for name in (b"dev-" + b"dsk-someone-main-1a-0123abcd", b"DEV-" + b"DSK-X", b"host.eu-west-1.amazon" + b".com",
                 b"https://example.AMAZON" + b".COM/x", b"ip-" + b"10-0-1-23.eu-west-1.compute" + b".internal",
                 b"ip-" + b"172-31-5-9", b"host.ec2" + b".internal"):
        assert INTERNAL_HOST.search(name), name
    for name in (b"Amazon Linux 2023", b"build-host", b"64-core AMD EPYC 9R14 host", b"dev-disk-1", b"zip-10-0-0-1",
                 b"ip-address", b"internal.compute"):
        assert not INTERNAL_HOST.search(name), name
    for call in (b"platform." + b"node()", b"socket." + b"gethostname()", b"socket." + b"getfqdn()",
                 b"platform." + b"uname()", b"os." + b"uname().nodename", b"echo $" + b"HOSTNAME",
                 b"x=$(" + b"hostname -f)", b"os.environ['HOST" + b"NAME']", b"uname " + b"-n", b"uname " + b"-an",
                 b"uname " + b"-a", b"uname " + b"--all", b'subprocess.run(["host' + b'name"])',
                 b"open('/etc/host" + b"name')", b"from platform import " + b"node",
                 b"from socket import " + b"getfqdn", b"HOST := $(shell host" + b"name)",
                 b"socket.gethostby" + b"addr(ip)", b"getname" + b"info(sa, n)"):
        assert HOSTNAME_READ.search(call), call
    for call in (b"platform.platform()", b"platform.machine()", b"socket.if_nameindex()", b"hostinfo.host_label()",
                 b"uname -s", b"uname -m", b"from platform import machine"):
        assert not HOSTNAME_READ.search(call), call


def test_no_internal_host_names_in_tracked_files():
    bad = matches(INTERNAL_HOST, [path for _, path in tracked()] + sorted(ALLOWED))
    assert not bad, ("an internal host name in a tracked file; record hostinfo.host_label() instead "
                     "(docs/build-host.md):\n" + "\n".join(bad))


def test_no_code_reads_the_machine_network_name():
    code = [path for _, path in tracked() if path not in HOSTNAME_READ_ALLOWED
            and (Path(path).suffix in CODE_SUFFIXES or Path(path).name in CODE_NAMES)]
    assert code
    bad = matches(HOSTNAME_READ, code)
    assert not bad, ("result files name the machine with hostinfo.host_label(), never its network name "
                     "(docs/build-host.md):\n" + "\n".join(bad))


def workflow_files():
    gh = ROOT / ".github"
    return sorted([*gh.glob("workflows/*.y*ml"), *gh.glob("actions/*/action.y*ml")])


USES = re.compile(r"^\s*(?:-\s+)?uses:\s*['\"]?([^'\"\s#]+)['\"]?\s*(#.*)?$")
PINNED = re.compile(r"^[\w.-]+/[\w.-]+(/[\w./-]+)?@[0-9a-f]{40}$")
TAG = re.compile(r"^#\s*v\d+(\.\d+)*\b")


def test_actions_are_pinned_to_a_commit_with_the_tag_in_a_comment():
    files = workflow_files()
    assert files, "no workflows found"
    bad = []
    for f in files:
        for n, line in enumerate(f.read_text().splitlines(), 1):
            m = USES.match(line)
            if not m or m.group(1).startswith("./"):
                continue
            if not PINNED.match(m.group(1)) or not TAG.match(m.group(2) or ""):
                bad.append(f"{f.relative_to(ROOT)}:{n}: {line.strip()}")
    assert not bad, ("pin each action to a full commit SHA with its tag as a comment, "
                     "e.g. 'uses: actions/checkout@<40-hex sha> # v7.0.1':\n" + "\n".join(bad))


def test_jobs_run_on_ubuntu_24_04():
    runs_on = [(f, n, line.split(":", 1)[1].strip().strip("'\""))
               for f in (ROOT / ".github" / "workflows").glob("*.y*ml")
               for n, line in enumerate(f.read_text().splitlines(), 1) if line.strip().startswith("runs-on:")]
    assert runs_on
    bad = [f"{f.name}:{n}: {v}" for f, n, v in runs_on if v != "ubuntu-24.04"]
    assert not bad, bad
